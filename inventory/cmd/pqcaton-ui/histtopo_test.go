// wholeMem — 이력 전체를 읽을 수 있는 메모리 pqcota 이력(노드를 늘어놓을 수 있다).
type wholeMem struct{ *history.MemStore }

func (wholeMem) Close() {}

// useEndpoints — 등록 엔드포인트를 메모리 목록으로 건다. 어느 조직으로 열었는지를 적어 둔다.
func useEndpoints(t *testing.T, eps inventory.EndpointLister, err error) *string {
	t.Helper()
	old, asked := openEndpoints, new(string)
	openEndpoints = func(_, org string) (inventory.EndpointLister, func(), error) {
		*asked = org
		return eps, func() {}, err
	}
	t.Cleanup(func() { openEndpoints = old })
	return asked
}

// IC-U227 — **02에서 「이력에서 앱별 통신 보기」를 열면 판정 조직의 pqcota 이력을 읽어 보이고, DOT은 `dot` 없이 받는다.**
//
// 화면은 판정 조직으로 연 이력과 그 조직의 등록 목록만 읽는다. 작업 폴더의 결과와 같은 정책으로 적재한 이력은 노드마다
// 「일치」이고, 다른 정책으로 적재하면 「다름」이다. 이력이 비었거나 읽지 못해도 화면은 뜨고 어느 조직을 읽었는지 밝힌다.
func TestHistoryTopologyScreen(t *testing.T) {
	s, _ := activationReady(t)
	survey := get(t, s, ui.ScreenSurvey+"?lang=ko").Body.String()
	if !strings.Contains(survey, `href="`+ui.ScreenHistTopo+`"`) || !strings.Contains(survey, "이력에서 앱별 통신 보기") {
		t.Fatal("02 has no link to the history topology")
	}

	meta := inventory.NewMemMetaStore()
	asked := useEndpoints(t, meta, nil)

	// 빈 이력.
	s.upstream, s.upstreamOrgName = wholeMem{history.NewMemStore()}, s.orgName()
	w := get(t, s, ui.ScreenHistTopo+"?lang=ko")
	if body := w.Body.String(); w.Code != http.StatusOK || !strings.Contains(body, "data-hist-empty") || !strings.Contains(body, "data-hist-org>"+s.orgName()+"<") {
		t.Fatalf("an empty history: %d\n%s", w.Code, body)
	}
	if *asked != s.orgName() {
		t.Errorf("the endpoints were read for %q, want the judgment organization %q", *asked, s.orgName())
	}

	// 작업 폴더와 같은 정책으로 적재한 이력: 노드마다 일치.
	s.upstream = wholeMem{ingestedUnder(t, s, s.scopeAssets, nil)}
	w = get(t, s, ui.ScreenHistTopo+"?lang=ko")
	body := w.Body.String()
	nodes := strings.Count(body, "data-hist-node=")
	if w.Code != http.StatusOK || nodes == 0 || strings.Count(body, `data-compare="same"`) != nodes {
		t.Fatalf("a history loaded from these results: %d, %d nodes, %d same\n%s", w.Code, nodes, strings.Count(body, `data-compare="same"`), body)
	}
	for _, sub := range []string{`data-hist-endpoints="0"`, "data-hist-counts", "data-hist-dot", `hx-get="` + ui.HistTopoPicturePath + `?lang=ko"`, `aria-current="step"`} {
		if !strings.Contains(body, sub) {
			t.Errorf("the screen lacks %q", sub)
		}
	}

	// 엔드포인트는 등록 목록에서만 온다.
	if err := meta.UpsertEndpoint(&inventoryv1.MachineEndpoint{NodeId: "web", Name: "Web gateway", Ip: "10.0.0.1"}); err != nil {
		t.Fatal(err)
	}
	if body := get(t, s, ui.ScreenHistTopo+"?lang=ko").Body.String(); !strings.Contains(body, `data-hist-endpoints="1"`) || !strings.Contains(body, "Web gateway") {
		t.Error("a registered endpoint does not show")
	}

	// DOT 내려받기: 상류가 낸 그대로, 받는 파일로.
	d := get(t, s, ui.HistTopoDotPath)
	if d.Code != http.StatusOK || !strings.HasPrefix(d.Body.String(), "digraph pqcota_topology {") ||
		!strings.HasPrefix(d.Header().Get("Content-Type"), "text/vnd.graphviz") || !strings.Contains(d.Header().Get("Content-Disposition"), "attachment") ||
		d.Header().Get("X-Content-Type-Options") != "nosniff" {
		t.Errorf("the DOT download: %d %v", d.Code, d.Header())
	}

	// 등록 목록을 읽지 못하면 화면은 503으로 뜨고 조직과 까닭을 적는다. 연결 정보는 나가지 않는다.
	useEndpoints(t, nil, errors.New("pqcota history: unreachable: timed out"))
	w = get(t, s, ui.ScreenHistTopo+"?lang=ko")
	if body := w.Body.String(); w.Code != http.StatusServiceUnavailable || !strings.Contains(body, "data-hist-error") ||
		!strings.Contains(body, "data-hist-org>"+s.orgName()+"<") || strings.Contains(body, "memory://tests") {
		t.Errorf("an unreadable history: %d\n%s", w.Code, body)
	}
	if d := get(t, s, ui.HistTopoDotPath); d.Code != http.StatusServiceUnavailable || strings.Contains(d.Body.String(), "digraph") {
		t.Errorf("the DOT download of an unreadable history: %d", d.Code)
	}
}

