// genpin — go.mod 이 고정한 상류 모듈의 판과 go.sum 의 내용 해시(h1)를 collectorver 의 생성 코드로 적는다.
//
// 화면은 수집기의 빌드 정보에 실린 주 모듈(pqcota-discovery)의 판과 h1 을 이 값과 견준다. 화면은 pqcota-discovery 를
// 링크하지 않으므로 자기 빌드 정보에서 그 h1 을 얻을 수 없다. 그래서 리포의 go.mod · go.sum 에서 만들어 코드에 고정하고,
// `make verify-generated` 와 collectorver 의 시험이 낡은 값을 막는다.
//
// usage: go run ./tools/genpin [-root .] [-out pkg/inventory/collectorver/pin_gen.go] [-check]
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// modules — 고정 값을 적을 상류 모듈.
var modules = []string{
	"github.com/randyinthedev-hash/pqcota-common",
	"github.com/randyinthedev-hash/pqcota-discovery",
	"github.com/randyinthedev-hash/pqcota-inventory",
	"github.com/randyinthedev-hash/pqcota-provisioning",
}

var requireLine = regexp.MustCompile(`^\s*(github\.com/randyinthedev-hash/pqcota[a-z-]*)\s+(v\S+)`)

// Pins — 모듈마다 판과 h1.
type pin struct{ version, sum string }

// read 는 go.mod 의 require 판과 go.sum 의 h1 을 읽는다.
func read(root string) (map[string]pin, error) {
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil, err
	}
	versions := map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(mod))
	for sc.Scan() {
		if m := requireLine.FindStringSubmatch(sc.Text()); m != nil {
			versions[m[1]] = m[2]
		}
	}
	sum, err := os.ReadFile(filepath.Join(root, "go.sum"))
	if err != nil {
		return nil, err
	}
	// 모듈 zip 의 h1 만 읽는다(`<모듈> <판>/go.mod h1:…` 줄은 go.mod 파일의 해시라 고르지 않는다). 같은 모듈 · 판에 서로 다른
	// h1 이 있으면 go.sum 이 모순이므로 생성하지 않는다.
	sums := map[string]string{}
	sc = bufio.NewScanner(bytes.NewReader(sum))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) != 3 || strings.HasSuffix(f[1], "/go.mod") {
			continue
		}
		k := f[0] + "@" + f[1]
		if prev, ok := sums[k]; ok && prev != f[2] {
			return nil, fmt.Errorf("go.sum has two h1 values for %s %s (%s, %s)", f[0], f[1], prev, f[2])
		}
		sums[k] = f[2]
	}
	out := map[string]pin{}
	for _, m := range modules {
		v, ok := versions[m]
		if !ok {
			return nil, fmt.Errorf("go.mod does not require %s", m)
		}
		s, ok := sums[m+"@"+v]
		if !ok || !strings.HasPrefix(s, "h1:") {
			return nil, fmt.Errorf("go.sum has no h1 for %s %s (run go mod tidy)", m, v)
		}
		out[m] = pin{v, s}
	}
	return out, nil
}

// render 는 생성 코드를 만든다. 생성 코드의 주석은 영어로 둔다(Go 문자열에 한국어를 두지 않는 관문).
func render(p map[string]pin) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/genpin from go.mod and go.sum; DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-FileCopyrightText: 2026 SNT Soft Co., Ltd.\n// SPDX-License-Identifier: BUSL-1.1\n\n")
	b.WriteString("package collectorver\n\n")
	b.WriteString("// Pinned holds the upstream modules this repository requires: the version in go.mod and the content hash (h1) in go.sum.\n")
	b.WriteString("var Pinned = map[string]Pin{\n")
	keys := make([]string, 0, len(p))
	for k := range p {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: {Version: %q, Sum: %q},\n", k, p[k].version, p[k].sum)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func main() {
	root := flag.String("root", ".", "repository root (go.mod and go.sum)")
	out := flag.String("out", filepath.Join("pkg", "inventory", "collectorver", "pin_gen.go"), "generated file")
	check := flag.Bool("check", false, "fail when the generated file is stale instead of writing it")
	flag.Parse()
	p, err := read(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genpin:", err)
		os.Exit(1)
	}
	src, err := render(p)
	if err != nil {
		fmt.Fprintln(os.Stderr, "genpin:", err)
		os.Exit(1)
	}
	target := filepath.Join(*root, *out)
	if *check {
		cur, _ := os.ReadFile(target)
		if !bytes.Equal(cur, src) {
			fmt.Fprintf(os.Stderr, "✗ %s is stale: go.mod or go.sum changed; run go run ./tools/genpin and commit it\n", *out)
			os.Exit(1)
		}
		fmt.Printf("✓ %s matches go.mod and go.sum\n", *out)
		return
	}
	if err := os.WriteFile(target, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genpin:", err)
		os.Exit(1)
	}
}
