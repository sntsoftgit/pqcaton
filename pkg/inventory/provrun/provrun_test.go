// IC-PR1 — **화면이 돌리는 플레이북은 설정 파일만 놓는 것이다.** 생성기가 낸 설정 배치 플레이북에서는 노드마다 기대하는 작업
// 이름이 순서대로 읽히고 막는 것이 없다. 파일 내용 안의 `src:`는 모듈 인자로 읽지 않는다. provider 모듈을 놓는 작업 · 그
// 무결성 확인 · L3 훅 · 수동 단계 주석은 저마다의 까닭으로 막힌다.
func TestOnlyConfigPlacementIsRunnable(t *testing.T) {
	pb := ParsePlaybook([]byte(configOnly))
	if pb.Malformed || len(pb.Unsupported()) != 0 {
		t.Fatalf("config-only playbook: malformed=%v unsupported=%v", pb.Malformed, pb.Unsupported())
	}
	if got := strings.Join(pb.Nodes(), ","); got != "pay-app,pay-db" {
		t.Errorf("nodes = %s", got)
	}
	want := []string{"staging directory", "config directory", "place the config fragment (/etc/pqcota/openssl-pqc.cnf)"}
	for i, task := range pb.Plays[1].Tasks {
		if task.Name != want[i] {
			t.Errorf("task %d = %q, want %q", i, task.Name, want[i])
		}
	}
	got := map[string]int{}
	for _, u := range ParsePlaybook([]byte(providerInject)).Unsupported() {
		got[u.Why]++
	}
	if got[WhyProvider] != 3 || got[WhyL3] != 1 || got[WhyManual] != 1 || len(got) != 3 {
		t.Errorf("unsupported by reason = %v, want provider 3 · l3 1 · manual 1", got)
	}
}

// IC-PR2 — **모르는 꼴은 돌리지 않는다.** 생성기가 내지 않는 줄(손으로 넣은 작업 열쇠 · 다른 모듈 · play 밖의 줄)이 하나라도
// 있으면 Malformed이거나 「모르는 종류」로 막힌다. 패턴 문자가 든 노드 이름도 막힌다(Ansible이 한 노드로 읽지 않는다).
func TestUnknownShapesAreNotRunnable(t *testing.T) {
	for name, edit := range map[string]func(string) string{
		"extra task key": func(s string) string {
			return strings.Replace(s, "  become: true\n", "  become: true\n  serial: 1\n", 1)
		},
		"delegate": func(s string) string {
			return strings.Replace(s, "    - name: config directory\n", "    - name: config directory\n      delegate_to: localhost\n", 1)
		},
		"empty":    func(string) string { return "# nothing\n" },
		"no tasks": func(string) string { return "- name: x\n  hosts: [\"a\"]\n  become: true\n  tasks:\n" },
	} {
		if !ParsePlaybook([]byte(edit(configOnly))).Malformed {
			t.Errorf("%s: not reported as malformed", name)
		}
	}
	other := strings.Replace(configOnly, "ansible.builtin.file: { path: /opt/pqcota", "ansible.builtin.command: { cmd: /opt/pqcota", 1)
	if u := ParsePlaybook([]byte(other)).Unsupported(); len(u) != 1 || u[0].Why != WhyUnknown {
		t.Errorf("another module: %v", u)
	}
	for _, n := range []string{"all", "pay-db"} {
		if !NodeNameOK(n) {
			t.Errorf("%q should be usable", n)
		}
	}
	for _, n := range []string{"pay*", "a:b", "!x", "a,b", "", "a b", "-x"} {
		if NodeNameOK(n) {
			t.Errorf("%q should not be usable as a node name", n)
		}
	}
	pat := strings.Replace(configOnly, `hosts: ["pay-db"]`, `hosts: ["pay*"]`, 1)
	if u := ParsePlaybook([]byte(pat)).Unsupported(); len(u) != 1 || u[0].Node != "pay*" {
		t.Errorf("a pattern as the node: %v", u)
	}
}

// rec — 실행 기록을 줄 단위로 짓는다. callback이 쓰는 그대로의 순서다.
type rec struct {
	run   string
	lines []string
	task  int
}

func newRec(run string, check bool) *rec {
	r := &rec{run: run}
	r.lines = append(r.lines, strings.TrimSuffix(string(Header(run)), "\n"))
	r.add("ready", nil)
	r.add("begin", map[string]any{"check": check})
	return r
}

func (r *rec) add(ev string, f map[string]any) *rec {
	m := map[string]any{"seq": len(r.lines), "run": r.run, "ev": ev}
	for k, v := range f {
		m[k] = v
	}
	b, _ := json.Marshal(m)
	r.lines = append(r.lines, string(b))
	return r
}

// node — 한 노드의 play. statuses는 Gathering Facts부터의 결과다. "-"는 시작만 하고 결과가 없는 것, ""는 거기서 멈춘 것이다.
func (r *rec) node(p Play, statuses ...string) *rec {
	r.add("play", map[string]any{"hosts": []string{p.Node}})
	names := append([]string{GatherTask}, taskNames(p)...)
	for i, st := range statuses {
		if st == "" {
			break
		}
		r.task++
		id := fmt.Sprint("t", r.task)
		r.add("task", map[string]any{"task": id, "name": names[i]})
		r.add("start", map[string]any{"host": p.Node, "task": id})
		if st != "-" {
			r.add("result", map[string]any{"host": p.Node, "task": id, "status": st})
		}
	}
	return r
}

func (r *rec) end() *rec     { return r.add("end", nil) }
func (r *rec) bytes() []byte { return []byte(strings.Join(r.lines, "\n") + "\n") }
func taskNames(p Play) []string {
	var out []string
	for _, t := range p.Tasks {
		out = append(out, t.Name)
	}
	return out
}

func three() []Play {
	tasks := []Task{{Name: "staging directory"}, {Name: "config directory"}, {Name: "place the config fragment (/etc/pqcota/x.cnf)"}}
	return []Play{{Node: "n1", Tasks: tasks}, {Node: "n2", Tasks: tasks}, {Node: "n3", Tasks: tasks}}
}

func states(v Verdict) string {
	var out []string
	for _, n := range v.Nodes {
		s := string(n.State)
		if n.Why != "" {
			s += "(" + n.Why + ")"
		}
		out = append(out, s)
	}
	return strings.Join(out, " ")
}

var okRes = &Result{Exit: 0}

// IC-PR3 — **미리 보기의 판정은 셋이다.** 기대한 작업이 모두 ok · changed이고 바뀔 것이 하나라도 있으면 「준비됨」이다. 빠짐없이
// ok이면 「적용할 변경 없음」이다. 하나라도 건너뛰었거나 빠졌거나 실패했으면 「미완료」다. changed가 0이라는 것만으로 뒤의 둘을
// 합치지 않는다: 작업 하나가 빠진 기록은 changed가 0이어도 「미완료」다.
func TestPreviewOutcomes(t *testing.T) {
	p := three()
	all := func(st string) *rec {
		r := newRec("A", true)
		for _, pl := range p {
			r.node(pl, "ok", st, st, st)
		}
		return r.end()
	}
	if v := Evaluate("A", true, p, all("changed").bytes(), okRes); v.Outcome != PreviewReady || !v.RecordWhole {
		t.Errorf("all changed: %s whole=%v %s", v.Outcome, v.RecordWhole, states(v))
	}
	if v := Evaluate("A", true, p, all("ok").bytes(), okRes); v.Outcome != PreviewNoChange {
		t.Errorf("all ok: %s", v.Outcome)
	}
	skipped := newRec("A", true).node(p[0], "ok", "ok", "skipped", "ok").node(p[1], "ok", "ok", "ok", "ok").node(p[2], "ok", "ok", "ok", "ok").end()
	if v := Evaluate("A", true, p, skipped.bytes(), okRes); v.Outcome != PreviewPartial || v.Nodes[0].State != NodeSkipped {
		t.Errorf("one skipped: %s %s", v.Outcome, states(v))
	}
	missing := newRec("A", true).node(p[0], "ok", "ok", "ok", "ok").node(p[1], "ok", "ok", "ok").node(p[2], "ok", "ok", "ok", "ok").end()
	if v := Evaluate("A", true, p, missing.bytes(), okRes); v.Outcome != PreviewPartial {
		t.Errorf("one task missing with nothing changed: %s, want incomplete", v.Outcome)
	}
	// 종료 코드가 0이 아니거나 감독이 끝냈으면 기록이 좋아 보여도 준비됨이 아니다.
	if v := Evaluate("A", true, p, all("changed").bytes(), &Result{Exit: 2}); v.Outcome != PreviewPartial {
		t.Errorf("exit 2: %s", v.Outcome)
	}
	if v := Evaluate("A", true, p, all("changed").bytes(), &Result{Reason: EndStopped}); v.Outcome != PreviewPartial {
		t.Errorf("stopped: %s", v.Outcome)
	}
}

// IC-PR4 — **이 실행의 온전한 기록만 승인한다.** 같은 계획 · 같은 노드 · 같은 작업을 앞서 미리 본 기록(실행 ID만 다르다)을 이
// 실행의 기록으로 주면 승인하지 않는다. 줄이 빠진 기록(순번이 끊긴다), 끝줄이 없는 기록, 줄 중간에서 끊긴 기록, 끝 뒤에 줄이
// 더 있는 기록, 적용 실행의 기록을 미리 보기로 읽는 것, 기대하지 않은 노드나 작업 이름이 든 기록도 그렇다. 기록이 없어도 그렇다.
func TestOnlyThisRunsWholeRecordApproves(t *testing.T) {
	p := three()
	good := func(run string, check bool) *rec {
		r := newRec(run, check)
		for _, pl := range p {
			r.node(pl, "ok", "changed", "changed", "changed")
		}
		return r.end()
	}
	whole := good("B", true).bytes()
	if v := Evaluate("B", true, p, whole, okRes); v.Outcome != PreviewReady {
		t.Fatalf("the run's own record: %s", v.Outcome)
	}
	lines := strings.Split(strings.TrimSuffix(string(whole), "\n"), "\n")
	join := func(l []string) []byte { return []byte(strings.Join(l, "\n") + "\n") }
	other := three()
	other[2].Node = "n9"
	renamed := three()
	renamed[1].Tasks = append([]Task(nil), renamed[1].Tasks...)
	renamed[1].Tasks[2].Name = "place the config fragment (/etc/other)"
	for name, c := range map[string]struct {
		plays  []Play
		record []byte
	}{
		"an earlier run of the same plan": {p, good("A", true).bytes()},
		"a line missing":                  {p, join(append(append([]string{}, lines[:9]...), lines[10:]...))},
		"no end":                          {p, join(lines[:len(lines)-1])},
		"cut mid-line":                    {p, whole[:len(whole)-20]},
		"a line after the end":            {p, good("B", true).end().bytes()},
		"an apply run's record":           {p, good("B", false).bytes()},
		"another node":                    {other, whole},
		"another task name":               {renamed, whole},
		"no record":                       {p, nil},
	} {
		if v := Evaluate("B", true, c.plays, c.record, okRes); v.Outcome != PreviewPartial || v.RecordWhole {
			t.Errorf("%s: outcome=%s whole=%v, want incomplete", name, v.Outcome, v.RecordWhole)
		}
	}
}

// IC-PR5 — **노드의 상태는 실행 기록에서만 온다.** 첫째 노드 완료 → 둘째 노드 실패 → 셋째 노드 미시작이 고정 사례다. 그 밖에:
// 첫 작업에서 접속하지 못한 노드는 「접속하지 못함」, 시작한 작업의 결과가 없는 노드는 「결과를 알 수 없음」이고 그 이유는
// 감독이 끝낸 까닭을 따른다(상한 초과 · 중지 · 기록 중단). 감독이 작업 사이에서 끝낸 노드는 「일부 작업만 끝남」이고, 까닭 없이
// 작업 사이에서 끊긴 기록의 노드는 「결과를 알 수 없음」이다(뒤 작업이 기록 없이 돌았는지 알 수 없다).
func TestNodeStatesComeFromTheRecord(t *testing.T) {
	p := three()
	fixed := newRec("R", false).node(p[0], "ok", "changed", "changed", "changed").node(p[1], "ok", "changed", "failed").end()
	v := Evaluate("R", false, p, fixed.bytes(), &Result{Exit: 2})
	if got := states(v); got != "done partial(task-failed) not-run" || v.Outcome != ApplyPartial {
		t.Errorf("the fixed case: %s (%s)", got, v.Outcome)
	}
	if v.Nodes[1].Tasks[3].Status != TaskNotStarted || v.Nodes[2].Tasks[0].Status != TaskNotStarted {
		t.Errorf("tasks after the failure should read not-started: %v %v", v.Nodes[1].Tasks, v.Nodes[2].Tasks)
	}
	for name, c := range map[string]struct {
		r    *rec
		res  *Result
		want string
	}{
		"all done":                {newRec("R", false).node(p[0], "ok", "changed", "ok", "changed").node(p[1], "ok", "ok", "ok", "changed").node(p[2], "ok", "ok", "ok", "ok").end(), okRes, "done done done"},
		"unreachable at first":    {newRec("R", false).node(p[0], "unreachable").end(), &Result{Exit: 4}, "unreachable(unreachable) not-run not-run"},
		"failed before a change":  {newRec("R", false).node(p[0], "ok", "failed").end(), &Result{Exit: 2}, "failed(task-failed) not-run not-run"},
		"unreachable midway":      {newRec("R", false).node(p[0], "ok", "changed", "unreachable").end(), &Result{Exit: 4}, "partial(unreachable) not-run not-run"},
		"stalled":                 {newRec("R", false).node(p[0], "ok", "changed", "changed", "changed").node(p[1], "ok", "changed", "changed", "-"), &Result{Exit: 99, Reason: EndStall}, "done unknown(stalled) not-run"},
		"stopped mid-task":        {newRec("R", false).node(p[0], "ok", "changed", "-"), &Result{Exit: 99, Reason: EndStopped}, "unknown(stopped) not-run not-run"},
		"screen gone mid-task":    {newRec("R", false).node(p[0], "ok", "-"), &Result{Exit: 99, Reason: EndOrphaned}, "unknown(stopped) not-run not-run"},
		"stopped between tasks":   {newRec("R", false).node(p[0], "ok", "changed"), &Result{Exit: 99, Reason: EndStopped}, "partial(stopped) not-run not-run"},
		"record cut mid-task":     {newRec("R", false).node(p[0], "ok", "changed", "-"), nil, "unknown(record-cut) not-run not-run"},
		"record cut between":      {newRec("R", false).node(p[0], "ok", "changed"), nil, "unknown(record-cut) not-run not-run"},
		"nothing remote happened": {newRec("R", false), &Result{Exit: 250, Reason: EndNotReady}, "not-run not-run not-run"},
	} {
		v := Evaluate("R", false, p, c.r.bytes(), c.res)
		if got := states(v); got != c.want {
			t.Errorf("%s: %s, want %s", name, got, c.want)
		}
		if (v.Outcome == ApplyDone) != (name == "all done") {
			t.Errorf("%s: outcome %s", name, v.Outcome)
		}
	}
}

// IC-PR6 — **적용 권한은 미리 본 묶음에 묶이고, 10분 살고, 한 번만 쓴다.** 끝난 지 10분이 되는 순간부터 만료다. 묶음의 한
// 자리라도 달라지면 남은 시간과 무관하게 「달라짐」이다. 쓰기는 유효할 때만 되고, 두 번째는 「이미 씀」이며, 동시에 여럿이 써도
// 하나만 된다. 만료됐거나 달라진 권한은 써지지 않고 쓴 표시도 남지 않는다.
func TestGrantIsBoundTimedAndSingleUse(t *testing.T) {
	bind := Binding{"plan": "p1", "playbook": "b1", "inventory": "i1", "vars": "v1", "config": "c1"}
	digest := bind.Digest()
	ended := time.Date(2026, 11, 26, 9, 0, 0, 0, time.UTC)
	g := NewGrant("R", digest, ended)
	if g.State(ended.Add(GrantTTL-time.Second), digest, false) != GrantValid {
		t.Error("a second before ten minutes should be valid")
	}
	if g.State(ended.Add(GrantTTL), digest, false) != GrantExpired {
		t.Error("at ten minutes it should be expired")
	}
	for k := range bind {
		changed := Binding{}
		for a, b := range bind {
			changed[a] = b
		}
		changed[k] += "x"
		if g.State(ended.Add(time.Minute), changed.Digest(), false) != GrantChanged {
			t.Errorf("a change in %s should invalidate the grant", k)
		}
		if g.State(ended.Add(time.Hour), changed.Digest(), false) != GrantChanged {
			t.Errorf("a change in %s should read as changed even after expiry", k)
		}
	}

	dir := t.TempDir()
	if err := Consume(dir, ended, digest); !errors.Is(err, ErrGrant{GrantNone}) {
		t.Errorf("no grant: %v", err)
	}
	if err := WriteGrant(dir, g); err != nil {
		t.Fatal(err)
	}
	for when, want := range map[time.Duration]GrantState{GrantTTL: GrantExpired} {
		if err := Consume(dir, ended.Add(when), digest); !errors.Is(err, ErrGrant{want}) || Used(dir) {
			t.Errorf("consume at +%s: %v used=%v", when, err, Used(dir))
		}
	}
	if err := Consume(dir, ended.Add(time.Minute), digest+"x"); !errors.Is(err, ErrGrant{GrantChanged}) || Used(dir) {
		t.Errorf("consume with another binding: %v used=%v", err, Used(dir))
	}
	var wg sync.WaitGroup
	var mu sync.Mutex
	won := 0
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if Consume(dir, ended.Add(time.Minute), digest) == nil {
				mu.Lock()
				won++
				mu.Unlock()
			}
		}()
	}
	wg.Wait()
	if won != 1 {
		t.Errorf("%d of 8 concurrent uses succeeded, want 1", won)
	}
	if err := Consume(dir, ended.Add(2*time.Minute), digest); !errors.Is(err, ErrGrant{GrantUsed}) {
		t.Errorf("second use: %v", err)
	}
	if got, _ := ReadGrant(dir); got == nil || got.State(ended.Add(2*time.Minute), digest, Used(dir)) != GrantUsed {
		t.Error("a used grant should read as used")
	}
}

// IC-PR7 — **감독이 읽는 두 가지.** 준비 신호는 이 실행의 ID로 쓴 둘째 줄일 때만 준비됨이다(첫 줄만 있거나, 다른 실행의
// 것이거나, 줄이 끝나지 않았으면 아니다). 결과를 기다리는 작업은 시작이 있고 결과가 없는 (노드, 작업)이다.
func TestReadyAndPending(t *testing.T) {
	head := string(Header("R"))
	if head != `{"ev":"open","run":"R","seq":0}`+"\n" {
		t.Errorf("header = %q", head)
	}
	ready := `{"seq":1,"run":"R","ev":"ready"}` + "\n"
	if !Ready([]byte(head+ready), "R") {
		t.Error("header and ready should be ready")
	}
	for name, b := range map[string]string{"header only": head, "another run": head + strings.Replace(ready, `"R"`, `"Q"`, 1),
		"unfinished line": head + strings.TrimSuffix(ready, "\n"), "empty": ""} {
		if Ready([]byte(b), "R") {
			t.Errorf("%s: should not be ready", name)
		}
	}
	p := three()
	r := newRec("R", false).node(p[0], "ok", "changed", "-")
	if got := Pending(r.bytes()); len(got) != 1 || !strings.HasPrefix(got[0], "n1\x00") {
		t.Errorf("pending = %q", got)
	}
	if got := Pending(newRec("R", false).node(p[0], "ok", "changed").bytes()); len(got) != 0 {
		t.Errorf("nothing should be pending: %q", got)
	}
}
